// Export of the registry and spec sheets as LaTeX (IEEEtran) and MATLAB text.

import { GROUPS } from './params.js';

/** Escape text for LaTeX. */
export function latexEscape(s) {
  return String(s)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([%&#$_{}])/g, '\\$1')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/~/g, '\\textasciitilde{}');
}

function latexTable(caption, label, header, rows, wide) {
  const env = wide ? 'table*' : 'table';
  const cols = header.map(() => 'l').join(' ');
  const out = [
    `\\begin{${env}}[!t]`,
    '\\centering',
    `\\caption{${latexEscape(caption)}}`,
    `\\label{${label}}`,
    '\\footnotesize',
    `\\begin{tabular}{${cols}}`,
    '\\hline',
    header.map(latexEscape).join(' & ') + ' \\\\',
    '\\hline',
    ...rows.map((r) => r.map(latexEscape).join(' & ') + ' \\\\'),
    '\\hline',
    '\\end{tabular}',
    `\\end{${env}}`,
  ];
  return out.join('\n');
}

export function latexParamTable(reg, { wide = true } = {}) {
  const rows = [];
  for (const g of Object.keys(GROUPS)) {
    for (const p of reg.filter((x) => x.group === g)) {
      rows.push([p.label, String(p.value), p.unit, p.status, p.source]);
    }
  }
  return latexTable('Zaan converter parameters', 'tab:zaan-params', ['Parameter', 'Value', 'Unit', 'Status', 'Source'], rows, wide);
}

export function latexSpecSheet(block, rows, fmtValue) {
  const body = rows.map((r) => [r.name, fmtValue(r), r.status, r.line]);
  const label = 'tab:spec-' + block.toLowerCase().replace(/[^a-z]+/g, '-');
  return latexTable(`Specification: ${block}`, label, ['Quantity', 'Value', 'Status', 'Budget line'], body, false);
}

function matlabString(s) {
  return "'" + String(s).replace(/'/g, "''") + "'";
}

/** MATLAB struct with SI values, one field per parameter. */
export function matlabStruct(reg, name = 'zaan') {
  const lines = [`% Zaan parameters, SI units. Generated by the Zaan tool.`, `${name} = struct();`];
  for (const p of reg) {
    lines.push(
      `${name}.${p.id} = struct('value', ${Number((p.value * p.si).toPrecision(12))}, 'unit', ${matlabString(p.siUnit)}, ` +
        `'status', ${matlabString(p.status)}, 'source', ${matlabString(p.source)}, 'date', ${matlabString(p.date)});`
    );
  }
  return lines.join('\n');
}
