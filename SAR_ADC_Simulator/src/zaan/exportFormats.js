// Export of the registry and spec sheets as LaTeX (IEEEtran) and MATLAB text.

import { GROUPS } from './params.js';

/** Escape text for LaTeX. */
export function latexEscape(s) {
  return String(s)
    .replace(/\\/g, '\\textbackslash{}')
    .replace(/([%&#$_{}])/g, '\\$1')
    .replace(/\^/g, '\\textasciicircum{}')
    .replace(/~/g, '\\textasciitilde{}')
    .replace(/µ/g, '\\textmu{}')
    .replace(/²/g, '\\textsuperscript{2}')
    .replace(/×/g, '$\\times$')
    .replace(/σ/g, '$\\sigma$')
    .replace(/Δ/g, '$\\Delta$')
    .replace(/√/g, '$\\surd$');
}

function latexTable(caption, label, header, rows, wide) {
  const env = wide ? 'table*' : 'table';
  const cols = header.map(() => 'l').join(' ');
  const out = [
    `\\begin{${env}}[!t]`,
    '\\centering',
    `\\caption{${latexEscape(caption)}}`,
    `\\label{${label}}`,
    '\\footnotesize',
    `\\begin{tabular}{${cols}}`,
    '\\hline',
    header.map(latexEscape).join(' & ') + ' \\\\',
    '\\hline',
    ...rows.map((r) => r.map(latexEscape).join(' & ') + ' \\\\'),
    '\\hline',
    '\\end{tabular}',
    `\\end{${env}}`,
  ];
  return out.join('\n');
}

export function latexParamTable(reg, { wide = true } = {}) {
  const rows = [];
  for (const g of Object.keys(GROUPS)) {
    for (const p of reg.filter((x) => x.group === g)) {
      rows.push([p.label, String(p.value), p.unit]);
    }
  }
  return latexTable('Zaan converter parameters', 'tab:zaan-params', ['Parameter', 'Value', 'Unit'], rows, wide);
}

export function latexSpecSheet(block, rows, fmtValue) {
  const body = rows.map((r) => [r.name, fmtValue(r), r.line]);
  const label = 'tab:spec-' + block.toLowerCase().replace(/[^a-z]+/g, '-');
  return latexTable(`Specification: ${block}`, label, ['Quantity', 'Value', 'Budget line'], body, false);
}

/** MATLAB struct with SI values, one field per parameter, unit as a comment. */
export function matlabStruct(reg, name = 'zaan') {
  const lines = [`% Zaan parameters in SI units. Generated by the Zaan workbench.`, `${name} = struct();`];
  for (const p of reg) {
    const v = Number((p.value * p.si).toPrecision(12));
    lines.push(`${name}.${p.id} = ${v}; % ${p.siUnit}, ${p.label}${p.estimate ? ' (estimate)' : ''}`);
  }
  return lines.join('\n');
}
